package dev.lgonnet.nat2j.backend;

import com.squareup.javapoet.ClassName;
import com.squareup.javapoet.CodeBlock;
import com.squareup.javapoet.FieldSpec;
import com.squareup.javapoet.JavaFile;
import com.squareup.javapoet.MethodSpec;
import com.squareup.javapoet.TypeName;
import com.squareup.javapoet.TypeSpec;
import dev.lgonnet.nat2j.ir.Ir;
import dev.lgonnet.nat2j.lowering.LoweringNotImplemented;
import dev.lgonnet.nat2j.lowering.Names;
import dev.lgonnet.nat2j.types.NaturalType;

import java.io.PrintWriter;
import java.math.BigDecimal;
import java.math.RoundingMode;
import java.util.List;
import javax.lang.model.element.Modifier;

public final class JavaEmitter {

    public static final String PACKAGE = "nat2j.generated";

    private static final ClassName BIG_DECIMAL = ClassName.get(BigDecimal.class);
    private static final ClassName ROUNDING_MODE = ClassName.get(RoundingMode.class);
    private static final ClassName PRINT_WRITER = ClassName.get(PrintWriter.class);

    private int loopLocals;

    public JavaFile emit(Ir.Program program) {
        loopLocals = 0;
        String simpleName = Names.toTypeName(program.name());

        TypeSpec.Builder type = TypeSpec.classBuilder(simpleName)
                .addJavadoc("Generated by nat2j from Natural source. Do not edit.\n")
                .addModifiers(Modifier.PUBLIC, Modifier.FINAL);

        for (Ir.Var var : program.vars()) {
            type.addField(fieldInitialisedTheWayNaturalWould(var));
        }

        type.addMethod(MethodSpec.methodBuilder("run")
                .addModifiers(Modifier.PUBLIC)
                .addParameter(PRINT_WRITER, "out")
                .addCode(block(program.body()))
                .build());

        for (Ir.Routine routine : program.routines()) {
            type.addMethod(MethodSpec.methodBuilder(routine.javaName())
                    .addModifiers(Modifier.PRIVATE)
                    .addParameter(PRINT_WRITER, "out")
                    .addJavadoc("Natural subroutine $L.\n", routine.naturalName())
                    .addCode(block(routine.body()))
                    .build());
        }

        type.addMethod(MethodSpec.methodBuilder("main")
                .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
                .addParameter(String[].class, "args")
                .addStatement("$T out = new $T($T.out, true)", PRINT_WRITER, PRINT_WRITER, System.class)
                .addStatement("new $L().run(out)", simpleName)
                .addStatement("out.flush()")
                .build());

        addRuntimeHelpers(type);

        return JavaFile.builder(PACKAGE, type.build()).skipJavaLangImports(true).build();
    }

    private FieldSpec fieldInitialisedTheWayNaturalWould(Ir.Var var) {
        NaturalType type = var.type();
        FieldSpec.Builder field = FieldSpec.builder(type.javaType(), var.javaName(), Modifier.PRIVATE)
                .addJavadoc("$L ($L)\n", var.naturalName(), type);
        switch (type.kind()) {
            case A -> field.initializer("$S", " ".repeat(type.length()));
            case N, P -> field.initializer("new $T($S)", BIG_DECIMAL, zeroAtScale(type.scale()));
            case I -> field.initializer("0");
            case F -> field.initializer(type.length() == 4 ? "0f" : "0d");
            case L -> field.initializer("false");
            case B, D, T -> throw new LoweringNotImplemented("field format " + type);
        }
        return field.build();
    }

    private static String zeroAtScale(int scale) {
        return scale == 0 ? "0" : "0." + "0".repeat(scale);
    }

    private CodeBlock block(List<Ir.Stmt> stmts) {
        CodeBlock.Builder out = CodeBlock.builder();
        for (Ir.Stmt stmt : stmts) {
            out.add(statement(stmt));
        }
        return out.build();
    }

    private CodeBlock statement(Ir.Stmt stmt) {
        return switch (stmt) {
            case Ir.Assign a -> CodeBlock.builder()
                    .addStatement("this.$L = $L", a.target().javaName(),
                            fitValueToTargetField(a.value(), a.target().type()))
                    .build();

            case Ir.Emit e -> {
                CodeBlock.Builder args = CodeBlock.builder();
                for (int i = 0; i < e.operands().size(); i++) {
                    if (i > 0) {
                        args.add(", ");
                    }
                    args.add(expression(e.operands().get(i)));
                }
                yield CodeBlock.builder().addStatement("writeLine(out, $L)", args.build()).build();
            }

            case Ir.Branch b -> {
                CodeBlock.Builder out = CodeBlock.builder()
                        .beginControlFlow("if ($L)", expression(b.condition()))
                        .add(block(b.whenTrue()));
                if (!b.whenFalse().isEmpty()) {
                    out.nextControlFlow("else").add(block(b.whenFalse()));
                }
                yield out.endControlFlow().build();
            }

            case Ir.CountedLoop l -> countedLoop(l);

            case Ir.PostTestLoop l -> CodeBlock.builder()
                    .beginControlFlow("do")
                    .add(block(l.body()))
                    .endControlFlow("while (!($L))", expression(l.until()))
                    .build();

            case Ir.Call c -> CodeBlock.builder().addStatement("this.$L(out)", c.javaName()).build();
        };
    }

    private CodeBlock countedLoop(Ir.CountedLoop loop) {
        String var = loop.var().javaName();
        int id = loopLocals++;
        String limit = "limit" + id;
        String step = "step" + id;
        CodeBlock.Builder out = CodeBlock.builder();

        if (loop.var().type().kind() == NaturalType.Kind.I) {
            out.addStatement("int $L = $L", limit, asInt(loop.to()));
            out.addStatement("int $L = $L", step, asInt(loop.step()));
            out.addStatement("this.$L = $L", var, fitValueToTargetField(loop.from(), loop.var().type()));
            out.beginControlFlow("while ($L >= 0 ? this.$L <= $L : this.$L >= $L)",
                    step, var, limit, var, limit);
            out.add(block(loop.body()));
            out.addStatement("this.$L += $L", var, step);
        } else {
            out.addStatement("$T $L = $L", BIG_DECIMAL, limit, asBigDecimal(loop.to()));
            out.addStatement("$T $L = $L", BIG_DECIMAL, step, asBigDecimal(loop.step()));
            out.addStatement("this.$L = $L", var, fitValueToTargetField(loop.from(), loop.var().type()));
            out.beginControlFlow(
                    "while ($L.signum() >= 0 ? this.$L.compareTo($L) <= 0 : this.$L.compareTo($L) >= 0)",
                    step, var, limit, var, limit);
            out.add(block(loop.body()));
            out.addStatement("this.$L = this.$L.add($L)", var, var, step);
        }
        return out.endControlFlow().build();
    }

    private CodeBlock fitValueToTargetField(Ir.Expr value, NaturalType target) {
        NaturalType source = value.type();
        CodeBlock raw = expression(value);

        if (target.kind() == NaturalType.Kind.A) {
            rejectIfNotAssignable(source.kind() == NaturalType.Kind.A, source, target);
            return CodeBlock.of("padOrTruncate($L, $L)", raw, target.length());
        }
        if (target.isDecimal()) {
            rejectIfNotAssignable(source.isNumeric(), source, target);
            return CodeBlock.of("truncateToScale($L, $L)", asBigDecimal(value), target.scale());
        }
        if (target.kind() == NaturalType.Kind.I) {
            rejectIfNotAssignable(source.isNumeric(), source, target);
            // TODO Natural raises an error on overflow, intValue() just wraps
            return switch (target.length()) {
                case 1 -> CodeBlock.of("(byte) $L", asInt(value));
                case 2 -> CodeBlock.of("(short) $L", asInt(value));
                default -> asInt(value);
            };
        }
        if (target.kind() == NaturalType.Kind.F) {
            rejectIfNotAssignable(source.isNumeric(), source, target);
            return target.length() == 4
                    ? CodeBlock.of("$L.floatValue()", asBigDecimal(value))
                    : CodeBlock.of("$L.doubleValue()", asBigDecimal(value));
        }
        if (target.kind() == NaturalType.Kind.L) {
            rejectIfNotAssignable(source.kind() == NaturalType.Kind.L, source, target);
            return raw;
        }
        throw new LoweringNotImplemented("assignment to a " + target + " field");
    }

    private void rejectIfNotAssignable(boolean assignable, NaturalType source, NaturalType target) {
        if (!assignable) {
            throw new IllegalStateException("cannot move " + source + " into " + target
                    + ", no cross-format MOVE yet");
        }
    }

    private CodeBlock expression(Ir.Expr expr) {
        return switch (expr) {
            case Ir.Ref r -> CodeBlock.of("this.$L", r.javaName());
            case Ir.Const c -> constant(c);
            case Ir.Arith a -> arithmetic(a);
            case Ir.Compare c -> comparison(c);
            case Ir.Logic l -> logic(l);
        };
    }

    private CodeBlock arithmetic(Ir.Arith arith) {
        CodeBlock left = asBigDecimal(arith.left());
        if (arith.op() == Ir.Op.NEG) {
            return CodeBlock.of("$L.negate()", left);
        }
        CodeBlock right = asBigDecimal(arith.right());
        return switch (arith.op()) {
            case ADD -> CodeBlock.of("$L.add($L)", left, right);
            case SUB -> CodeBlock.of("$L.subtract($L)", left, right);
            case MUL -> CodeBlock.of("$L.multiply($L)", left, right);
            case DIV -> CodeBlock.of("$L.divide($L, $L, $T.DOWN)",
                    left, right, arith.type().scale(), ROUNDING_MODE);
            case NEG -> throw new IllegalStateException("handled above");
        };
    }

    private CodeBlock comparison(Ir.Compare compare) {
        String op = javaOperator(compare.op());
        NaturalType left = compare.left().type();

        if (left.kind() == NaturalType.Kind.A) {
            return CodeBlock.of("(compareAlpha($L, $L) $L 0)",
                    expression(compare.left()), expression(compare.right()), op);
        }
        if (left.kind() == NaturalType.Kind.L) {
            if (compare.op() != Ir.Cmp.EQ && compare.op() != Ir.Cmp.NE) {
                throw new IllegalStateException("cannot order logical values");
            }
            return CodeBlock.of("($L $L $L)",
                    expression(compare.left()), op, expression(compare.right()));
        }
        return CodeBlock.of("($L.compareTo($L) $L 0)",
                asBigDecimal(compare.left()), asBigDecimal(compare.right()), op);
    }

    private String javaOperator(Ir.Cmp cmp) {
        return switch (cmp) {
            case EQ -> "==";
            case NE -> "!=";
            case LT -> "<";
            case LE -> "<=";
            case GT -> ">";
            case GE -> ">=";
        };
    }

    private CodeBlock logic(Ir.Logic logic) {
        List<Ir.Expr> operands = logic.operands();
        return switch (logic.op()) {
            case AND -> CodeBlock.of("($L && $L)",
                    expression(operands.get(0)), expression(operands.get(1)));
            case OR -> CodeBlock.of("($L || $L)",
                    expression(operands.get(0)), expression(operands.get(1)));
            case NOT -> CodeBlock.of("(!$L)", expression(operands.get(0)));
        };
    }

    private CodeBlock asBigDecimal(Ir.Expr expr) {
        if (expr.type().isDecimal()) {
            return expression(expr);
        }
        if (!expr.type().isNumeric()) {
            throw new IllegalStateException("not a number: " + expr.type());
        }
        return CodeBlock.of("$T.valueOf($L)", BIG_DECIMAL, expression(expr));
    }

    private CodeBlock asInt(Ir.Expr expr) {
        return CodeBlock.of("$L.intValue()", asBigDecimal(expr));
    }

    private CodeBlock constant(Ir.Const constant) {
        Object value = constant.value();
        if (value instanceof String s) {
            return CodeBlock.of("$S", s);
        }
        if (value instanceof BigDecimal d) {
            return CodeBlock.of("new $T($S)", BIG_DECIMAL, d.toPlainString());
        }
        if (value instanceof Boolean b) {
            return CodeBlock.of("$L", b);
        }
        throw new LoweringNotImplemented("constant of type " + value.getClass().getSimpleName());
    }

    private void addRuntimeHelpers(TypeSpec.Builder type) {
        type.addMethod(MethodSpec.methodBuilder("padOrTruncate")
                .addModifiers(Modifier.PRIVATE, Modifier.STATIC)
                .returns(String.class)
                .addParameter(String.class, "value")
                .addParameter(TypeName.INT, "length")
                .addStatement("String v = value == null ? \"\" : value")
                .beginControlFlow("if (v.length() > length)")
                .addStatement("return v.substring(0, length)")
                .endControlFlow()
                .addStatement("return v + \" \".repeat(length - v.length())")
                .build());

        type.addMethod(MethodSpec.methodBuilder("truncateToScale")
                .addModifiers(Modifier.PRIVATE, Modifier.STATIC)
                .returns(BIG_DECIMAL)
                .addParameter(BIG_DECIMAL, "value")
                .addParameter(TypeName.INT, "scale")
                .addStatement("return value.setScale(scale, $T.DOWN)", ROUNDING_MODE)
                .build());

        // Natural pads both sides out to the longer one before comparing, so
        // 'AB' and 'AB   ' are equal and String.equals would be wrong here
        type.addMethod(MethodSpec.methodBuilder("compareAlpha")
                .addModifiers(Modifier.PRIVATE, Modifier.STATIC)
                .returns(TypeName.INT)
                .addParameter(String.class, "left")
                .addParameter(String.class, "right")
                .addStatement("int width = Math.max(left.length(), right.length())")
                .addStatement("return padOrTruncate(left, width).compareTo(padOrTruncate(right, width))")
                .build());

        type.addMethod(MethodSpec.methodBuilder("render")
                .addModifiers(Modifier.PRIVATE, Modifier.STATIC)
                .returns(String.class)
                .addParameter(Object.class, "value")
                .beginControlFlow("if (value instanceof $T d)", BIG_DECIMAL)
                .addStatement("return d.toPlainString()")
                .endControlFlow()
                .addStatement("return String.valueOf(value)")
                .build());

        type.addMethod(MethodSpec.methodBuilder("writeLine")
                .addModifiers(Modifier.PRIVATE, Modifier.STATIC)
                .addParameter(PRINT_WRITER, "out")
                .addParameter(Object[].class, "parts")
                .varargs(true)
                .addStatement("StringBuilder sb = new StringBuilder()")
                .beginControlFlow("for (int i = 0; i < parts.length; i++)")
                .beginControlFlow("if (i > 0)")
                .addStatement("sb.append(' ')")
                .endControlFlow()
                .addStatement("sb.append(render(parts[i]))")
                .endControlFlow()
                .addStatement("out.println(sb.toString())")
                .build());
    }
}
